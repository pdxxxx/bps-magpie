import "./build-ui.mjs";
import { mkdirSync,readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const version=JSON.parse(readFileSync(path.join(root,"package.json"),"utf8")).version;
if(!/^\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/.test(version))throw new Error("Invalid package version");
const platform = process.env.TARGET_OS || process.platform;
const arch = process.env.TARGET_ARCH || process.arch;
const goos = {win32: "windows", linux: "linux", darwin: "darwin"}[platform];
const goarch = {x64: "amd64", arm64: "arm64"}[arch];
if (!goos || !goarch) throw new Error(`Unsupported target: ${platform}/${arch}`);
mkdirSync(path.join(root, "bin"), {recursive:true});
const target = path.join(root, "bin", `bps-bridge-${platform}-${arch}${platform === "win32" ? ".exe" : ""}`);
const result = spawnSync("go", ["build", "-trimpath", "-ldflags=-s -w -X main.version="+version, "-o", target, "./cmd/bps-bridge"], {cwd:path.join(root,"bridge"),env:{...process.env,CGO_ENABLED:"0",GOOS:goos,GOARCH:goarch},stdio:"inherit",windowsHide:true});
if (result.error) throw result.error;
if (result.status) process.exit(result.status);
console.log(`Built ${target}`);
