import {readFileSync,writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
const ui=new URL("../ui/",import.meta.url);
const settings=readFileSync(new URL("settings.mjs",ui),"utf8");
const controller=readFileSync(new URL("app.js",ui),"utf8");
const entry='import {fieldsFromOptions,optionsFromFields} from "./settings.mjs";';
if(!controller.startsWith(entry))throw new Error("Update the UI bundle builder for the changed controller import");
const source=settings.replace(/^export (?=function )/gm,"")+"\n"+controller.slice(entry.length);
if(/^\s*(?:import|export)\b/m.test(source))throw new Error("The settings bundle must contain no module imports or exports");
// Magpie pages have an opaque sandbox origin; classic scripts need no CORS.
const bundled="// Generated by scripts/build-ui.mjs; edit app.js/settings.mjs instead.\n(async()=>{\n\"use strict\";\n"+source+"\n})();\n";
writeFileSync(new URL("app.bundle.js",ui),bundled);
console.log("Built "+fileURLToPath(new URL("app.bundle.js",ui)));
